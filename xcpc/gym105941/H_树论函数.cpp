#include <bits/stdc++.h>
using namespace std;

// https://codeforces.com/gym/105941
void solve()
{
    int s, l, r;
    cin >> s >> l >> r;
    cout << r - l + 1 << '\n';
}
signed main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    int t = 1;
    cin >> t;
    while (t--)
        solve();
    return 0;
}